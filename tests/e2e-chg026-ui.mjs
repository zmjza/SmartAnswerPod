import assert from 'node:assert/strict'
import { mkdtempSync, readFileSync, rmSync } from 'node:fs'
import { join } from 'node:path'
import { tmpdir } from 'node:os'
import { _electron as electron } from 'patchright'
import { pageCountForCourses, pageForCourse, pageSlice } from '../electron/core/course-pager.ts'

const userData = mkdtempSync(join(tmpdir(), 'kaida-chg026-ui-'))
const version = JSON.parse(readFileSync(new URL('../package.json', import.meta.url), 'utf8')).version
const app = await electron.launch({ args: ['.'], env: { ...process.env, VITE_DEV_SERVER_URL: '', KAIDA_E2E_USERDATA: userData, KAIDA_E2E_MOCK_COURSES: '1' } })
const renderer = (source) => app.evaluate(({ BrowserWindow }, script) => BrowserWindow.getAllWindows()[0].webContents.executeJavaScript(script), source)
try {
  const page = await app.firstWindow()
  await page.waitForLoadState('domcontentloaded')
  await page.getByText('学生账号', { exact: true }).first().click()
  await page.getByRole('button', { name: '粘贴批量导入' }).click()
  await page.locator('textarea').fill('姓名\t账号\t密码\n张三\t模拟1001\tpass-1001\n重复\t模拟1001\tpass-dup\n\n李四，模拟1002，pass-1002\n坏行 模拟1003')
  await page.getByRole('button', { name: '解析预览' }).click()
  await page.getByText('pass-1001', { exact: true }).waitFor()
  assert.match(await page.locator('section').last().innerText(), /空行|缺少密码/)
  assert.match(await page.locator('section').last().innerText(), /账号重复/)
  assert.match(await page.locator('section').last().innerText(), /预计导入 2 名学生/)
  assert.equal((await renderer('window.kaida.listAccounts()')).length, 0)
  await page.getByRole('button', { name: '取消' }).click()
  await page.getByRole('button', { name: '粘贴批量导入' }).click()
  await page.locator('textarea').fill('姓名,账号,密码\n张三,模拟1001,pass-1001\n李四,模拟1002,pass-1002')
  await page.getByRole('button', { name: '解析预览' }).click()
  await page.getByRole('button', { name: /进入二级确认/ }).click()
  await page.getByRole('heading', { name: '确认写入学生账号' }).waitFor()
  assert.match(await page.locator('body').innerText(), /pass-1001/)
  await page.getByRole('button', { name: '取消导入' }).click()
  await page.getByRole('button', { name: '取消', exact: true }).click()
  assert.equal((await renderer('window.kaida.listAccounts()')).length, 0, '取消二级确认后产生了账号')
  await page.getByRole('button', { name: '粘贴批量导入' }).click()
  await page.locator('textarea').fill('姓名,账号,密码\n张三,模拟1001,pass-1001\n李四,模拟1002,pass-1002')
  await page.getByRole('button', { name: '解析预览' }).click()
  await page.getByRole('button', { name: /进入二级确认/ }).click()
  await page.getByRole('button', { name: '确认写入 2 名' }).click()
  await page.waitForFunction(async () => {
    const accounts = await window.kaida.listAccounts()
    return accounts.length === 2
  })
  const accounts = JSON.parse(await renderer('window.kaida.listAccounts().then(JSON.stringify)'))
  assert.deepEqual(accounts.map((item) => item.account).sort(), ['模拟1001', '模拟1002'])
  const courses = Array.from({ length: 11 }, (_, i) => ({ name: `模拟课程${i + 1}` }))
  assert.equal(pageCountForCourses(courses, 10), 2)
  assert.equal(pageSlice(courses, 10, 2).length, 1)
  assert.equal(pageForCourse(courses, 10, '模拟课程11'), 2)
  assert.equal(pageForCourse(courses, 10, '不存在'), 1)
  await page.getByText('工作台', { exact: true }).first().click()
  await page.locator('#course-list').waitFor()
  assert.equal(await page.locator('#student-meta').getByText('登录账号').count(), 1)
  assert.match(await page.locator('#student-meta').innerText(), /模拟1001/)
  assert.equal(await page.locator('#student-switcher').evaluate((el) => getComputedStyle(el).flexDirection), 'column')
  assert.equal(await page.locator('#course-list').evaluate((el) => getComputedStyle(el).height), '360px', '课程列表没有固定高度')
  assert.equal(await page.locator('#course-list .course-item').count(), 1, '当前课程自动跳页未定位到最后一页')
  assert.match(await page.locator('#course-list .course-item').first().innerText(), /模拟课程11/)
  assert.equal(await page.getByRole('button', { name: '上一页课程' }).isDisabled(), false)
  assert.equal(await page.getByRole('button', { name: '下一页课程' }).locator('.material-symbols-outlined').textContent(), 'chevron_right')
  assert.equal(await page.getByRole('button', { name: '下一页课程' }).isDisabled(), true)
  await page.getByRole('button', { name: '上一页课程' }).click()
  await page.getByText('1/2', { exact: true }).waitFor()
  assert.equal(await page.locator('#course-list .course-item').count(), 10)
  await page.getByRole('button', { name: '下一页课程' }).click()
  await page.getByText('2/2', { exact: true }).waitFor()
  await app.evaluate(() => { process.env.KAIDA_E2E_MOCK_ACTIVE_COURSE = '模拟课程2' })
  await renderer('window.kaida.saveSettings({})')
  await page.getByText('1/2', { exact: true }).waitFor()
  assert.match(await page.locator('#course-list .course-item').first().innerText(), /模拟课程1/)
  await app.evaluate(async ({ BrowserWindow }) => {
    const window = BrowserWindow.getAllWindows()[0]
    const snap = await window.webContents.executeJavaScript('window.kaida.snapshot()')
    window.webContents.send('kaida:snapshot', { ...snap, running: true })
  })
  await page.waitForFunction(() => document.querySelector('#btn-primary-action')?.disabled === true)
  assert.equal(await page.locator('#btn-stop-all').isDisabled(), false)
  await renderer('window.kaida.saveSettings({})')
  for (const account of accounts) await renderer(`window.kaida.removeAccount(${JSON.stringify(account.local_id)})`)
  assert.equal((await renderer('window.kaida.listAccounts()')).length, 0, '模拟账号清理后仍有残留')
  assert.equal(await page.locator('header img[alt="开大智达舱 Logo"]').evaluate((img) => img.complete && img.naturalWidth > 0), true)
  await page.getByText(`v${version}`, { exact: true }).waitFor()
  await page.getByText('设置', { exact: true }).first().click()
  assert.equal(await page.locator('#supabase-url').isVisible(), false)
  assert.equal(await page.locator('#supabase-anon').isVisible(), false)
  const cloud = await page.getByText('云端与接口连接', { exact: true }).locator('xpath=ancestor::div[contains(@class,"rounded-2xl")][1]').boundingBox()
  const runtime = await page.getByText('运行环境与调试', { exact: true }).locator('xpath=ancestor::div[contains(@class,"rounded-2xl")][1]').boundingBox()
  const controls = await page.getByText('任务执行与并发控制', { exact: true }).boundingBox()
  assert.ok(cloud && runtime && controls && Math.abs(cloud.x - runtime.x) < 30 && runtime.y >= cloud.y + cloud.height && runtime.y - (cloud.y + cloud.height) < 40 && controls.x > cloud.x + 100, '运行环境卡片没有紧接在云端连接卡片下方')
 await page.locator('header').getByRole('button', { name: '检查更新', exact: true }).click()
  await page.locator('button.fixed').click()
  await page.getByRole('status').getByText('开发版跳过更新检查', { exact: true }).waitFor()
  console.log(JSON.stringify({ ok: true, preview: true, cancelNoWrite: true, confirmed: accounts.length, pagination: true }))
} finally {
  await app.close()
  rmSync(userData, { recursive: true, force: true })
}
